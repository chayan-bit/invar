const SOURCE: &[u8] =
    b"fn calc(n: i32) -> i32 { return n * 3; } fn peer(n: i32) -> i32 { return n + 7; }";
const FIB: &[u8] =
    b"fn fib(n: u32) -> i32 { if n < 2u32 { return 1; } return fib(n - 1u32) + fib(n - 2u32); }";

fn compile(source: &[u8], entry: &str, target: Target) -> provenance::ProvenancedArtifact {
    provenance::compile(source, entry, target, Limits::default()).unwrap()
}

#[test]
fn issue_gnet_05_provenance_reproducible_real_bytes_not_process_tokens() {
    let original = compile(SOURCE, "calc", Target::Cpu);
    for _ in 0..12 {
        let other = compile(SOURCE, "calc", Target::Cpu);
        assert_eq!(original.id(), other.id());
        assert_eq!(original.manifest(), other.manifest());
        let (net, proof) = other.checked_net();
        original.verify_net(net, proof).unwrap();
    }
    original.verify_source(SOURCE).unwrap();
    original
        .verify_artifact_bytes(original.artifact().source().as_bytes())
        .unwrap();
    original.verify_manifest(original.manifest()).unwrap();
    assert_eq!(
        original.manifest()["compiler_build"],
        env!("INVAR_BUILD_DIGEST")
    );
    assert_eq!(original.manifest()["source"]["bytes"], SOURCE.len());
    assert!(original.manifest().get("observed").is_none());
    assert!(original.manifest().get("executed").is_none());
}

#[test]
fn issue_gnet_05_provenance_source_changes_bind_actual_bytes_and_behavior() {
    let original = compile(SOURCE, "calc", Target::Cpu);
    // Trailing trivia changes source bytes but not the checked graph/emission.
    let mut trivia = SOURCE.to_vec();
    trivia.extend_from_slice(b"\n// source identity still includes this\n");
    let changed = compile(&trivia, "calc", Target::Cpu);
    assert_ne!(original.id(), changed.id());
    assert_eq!(original.manifest()["net"], changed.manifest()["net"]);
    assert_eq!(original.artifact().source(), changed.artifact().source());
    assert_eq!(original.verify_source(&trivia), Err(Error::SourceMismatch));

    let changed = compile(
        &SOURCE.replace_bytes(b"n * 3", b"n * 4"),
        "calc",
        Target::Cpu,
    );
    assert_ne!(original.id(), changed.id());
    assert_ne!(original.manifest()["net"], changed.manifest()["net"]);
    assert_ne!(original.artifact().source(), changed.artifact().source());
    let before = original
        .observe_oracle(&[eval::Value::I32(5)], oracle::Limits::default())
        .unwrap();
    let after = changed
        .observe_oracle(&[eval::Value::I32(5)], oracle::Limits::default())
        .unwrap();
    assert_eq!(
        before.observation().semantic.result,
        Ok(eval::Value::I32(15))
    );
    assert_eq!(
        after.observation().semantic.result,
        Ok(eval::Value::I32(20))
    );
}

trait ReplaceBytes {
    fn replace_bytes(&self, from: &[u8], to: &[u8]) -> Vec<u8>;
}
impl ReplaceBytes for [u8] {
    fn replace_bytes(&self, from: &[u8], to: &[u8]) -> Vec<u8> {
        String::from_utf8(self.to_vec())
            .unwrap()
            .replace(
                std::str::from_utf8(from).unwrap(),
                std::str::from_utf8(to).unwrap(),
            )
            .into_bytes()
    }
}

#[test]
fn issue_gnet_05_provenance_signature_entry_and_targets_are_distinct() {
    let cpu = compile(SOURCE, "calc", Target::Cpu);
    let peer = compile(SOURCE, "peer", Target::Cpu);
    let unsigned = compile(
        b"fn calc(n: u32) -> u32 { return n * 3u32; }",
        "calc",
        Target::Cpu,
    );
    assert_ne!(cpu.id(), peer.id());
    assert_ne!(cpu.id(), unsigned.id());
    assert_eq!(unsigned.manifest()["params"], json!(["U32"]));
    assert_eq!(unsigned.manifest()["result"], "U32");
    let cuda = compile(SOURCE, "calc", Target::Cuda);
    let metal = compile(SOURCE, "calc", Target::Metal);
    assert_ne!(cpu.id(), cuda.id());
    assert_ne!(cuda.id(), metal.id());
    assert_eq!(cuda.manifest()["target"], "Cuda");
    assert_eq!(metal.manifest()["target"], "Metal");
    assert!(cuda.manifest().get("observed").is_none());
}

#[test]
fn issue_gnet_05_provenance_every_compile_budget_is_bound() {
    let original = compile(SOURCE, "calc", Target::Cpu);
    // Accepted larger limits can leave generated bytes unchanged; they still
    // alter provenance. Iterate every currently public budget field.
    for field in 0..10 {
        let mut limits = Limits::default();
        match field {
            0 => limits.net.functions += 1,
            1 => limits.net.blocks += 1,
            2 => limits.net.instructions += 1,
            3 => limits.net.wires += 1,
            4 => limits.net.literal_bytes += 1,
            5 => limits.compiler.values += 1,
            6 => limits.compiler.places += 1,
            7 => limits.compiler.states += 1,
            8 => limits.compiler.frame_bytes += 1,
            9 => limits.compiler.source_bytes += 1,
            _ => unreachable!(),
        }
        let changed = provenance::compile(SOURCE, "calc", Target::Cpu, limits).unwrap();
        assert_ne!(original.id(), changed.id(), "budget {field}");
        assert_eq!(original.artifact().source(), changed.artifact().source());
    }
    let mut limits = Limits::default();
    limits.compiler.frame_bytes = 0;
    assert!(matches!(
        provenance::compile(SOURCE, "calc", Target::Cpu, limits),
        Err(Error::Compiler(_))
    ));
    limits = Limits::default();
    limits.net.functions = 0;
    assert!(matches!(
        provenance::compile(SOURCE, "calc", Target::Cpu, limits),
        Err(Error::Net(_))
    ));
}

#[test]
fn issue_gnet_05_provenance_forged_receipts_and_emitted_bytes_rejected() {
    let original = compile(SOURCE, "calc", Target::Cpu);
    for (path, replacement) in [
        (vec!["compiler_build"], json!("forged")),
        (vec!["version"], json!(99)),
        (vec!["net_contract"], json!(99)),
        (vec!["source", "sha256"], json!("forged")),
        (vec!["net", "sha256"], json!("forged")),
        (vec!["artifact", "sha256"], json!("forged")),
        (vec!["target"], json!("Cuda")),
        (vec!["params"], json!(["U32"])),
        (vec!["result"], json!("U32")),
        (vec!["storage", "frame_bytes"], json!(0)),
        (vec!["limits", "compiler", "values"], json!(1)),
    ] {
        let mut forged = original.manifest().clone();
        let mut node = &mut forged;
        for key in path {
            node = &mut node[key];
        }
        *node = replacement;
        assert_eq!(
            original.verify_manifest(&forged),
            Err(Error::ManifestMismatch)
        );
    }
    let mut forged = original.manifest().clone();
    forged["observed"] = json!({"backend": "cuda", "success": true});
    assert_eq!(
        original.verify_manifest(&forged),
        Err(Error::ManifestMismatch)
    );
    let mut emitted = original.artifact().source().as_bytes().to_vec();
    emitted.push(b'\n');
    assert_eq!(
        original.verify_artifact_bytes(&emitted),
        Err(Error::ArtifactMismatch)
    );
}

#[test]
fn issue_gnet_05_provenance_stale_annotations_and_valid_changed_net_rejected() {
    let original = compile(SOURCE, "calc", Target::Cpu);
    let (net, proof) = original.checked_net();
    let mut stale = net.clone();
    stale.agents[0].span.end += 1;
    assert!(matches!(
        original.verify_net(&stale, proof),
        Err(Error::Net(_))
    ));
    let mut stale = net.clone();
    stale.graph.wires[0].producer = usize::MAX;
    assert!(matches!(
        original.verify_net(&stale, proof),
        Err(Error::Net(_))
    ));

    // This candidate has its own valid proof, but it is no longer the source net.
    let mut mir = net.compiled_mir(proof).unwrap();
    let constant = mir.functions[0]
        .blocks
        .iter_mut()
        .flat_map(|b| &mut b.instructions)
        .find(|i| matches!(i.kind, mir::Operation::I32(3)))
        .unwrap();
    constant.kind = mir::Operation::I32(4);
    let changed = Net::encode(&mir, general_net::Limits::default()).unwrap();
    let proof = changed.verify().unwrap();
    assert_eq!(
        original.verify_net(&changed, &proof),
        Err(Error::NetMismatch)
    );
    let actual = oracle::observe_call(
        &changed,
        &proof,
        "calc",
        &[eval::Value::I32(5)],
        oracle::Limits::default(),
    )
    .unwrap();
    assert_eq!(actual.semantic.result, Ok(eval::Value::I32(20)));
}

#[test]
fn issue_gnet_05_provenance_observed_runtime_inputs_limits_and_events_separate() {
    let artifact = compile(FIB, "fib", Target::Cuda);
    let original_id = artifact.id().to_owned();
    let six = artifact
        .observe_oracle(&[eval::Value::U32(6)], oracle::Limits::default())
        .unwrap();
    let eight = artifact
        .observe_oracle(&[eval::Value::U32(8)], oracle::Limits::default())
        .unwrap();
    assert_eq!(six.observation().semantic.result, Ok(eval::Value::I32(13)));
    assert_eq!(
        eight.observation().semantic.result,
        Ok(eval::Value::I32(34))
    );
    assert_ne!(six.id(), eight.id());
    assert_eq!(eight.manifest()["backend"], "cpu_net_oracle");
    assert_eq!(eight.manifest()["artifact_id"], original_id);
    assert!(eight.observation().events.len() > 1000);
    assert_eq!(artifact.id(), original_id);
    assert!(artifact.manifest().get("observed").is_none());
    let limits = oracle::Limits {
        transitions: 0,
        ..oracle::Limits::default()
    };
    let limited = artifact
        .observe_oracle(&[eval::Value::U32(8)], limits)
        .unwrap();
    assert_eq!(
        limited.observation().failure,
        Some(oracle::ToolFailure::TransitionLimit)
    );
    assert_ne!(limited.id(), eight.id());
    let mut forged = eight.manifest().clone();
    forged["backend"] = json!("cuda");
    assert_eq!(eight.verify_manifest(&forged), Err(Error::ManifestMismatch));
    let mut forged = eight.manifest().clone();
    forged["observed"]["events_sha256"] = json!("forged");
    assert_eq!(eight.verify_manifest(&forged), Err(Error::ManifestMismatch));
    eight.verify_manifest(eight.manifest()).unwrap();
}

#[test]
fn issue_gnet_05_provenance_checked_boundary_rejects_bad_and_unsupported_source() {
    assert!(matches!(
        provenance::compile(b"\xff", "calc", Target::Cpu, Limits::default()),
        Err(Error::Source(_))
    ));
    assert!(matches!(
        provenance::compile(
            b"fn calc(n: i32) -> u32 { return n; }",
            "calc",
            Target::Cpu,
            Limits::default()
        ),
        Err(Error::Source(_))
    ));
    assert!(matches!(
        provenance::compile(SOURCE, "absent", Target::Cpu, Limits::default()),
        Err(Error::Compiler(_))
    ));
    // Whole-candidate admission cannot hide an unsupported unselected function.
    assert!(matches!(
        provenance::compile(
            b"fn calc(n: i32) -> i32 { return n; } fn unused() -> Array<i32> { let xs: Array<i32> = [1]; return xs; }",
            "calc",
            Target::Cuda,
            Limits::default()
        ),
        Err(Error::Compiler(_))
    ));
    assert!(matches!(
        provenance::compile(
            &vec![b' '; 1024 * 1024 + 1],
            "calc",
            Target::Cpu,
            Limits::default()
        ),
        Err(Error::Limit)
    ));
}

