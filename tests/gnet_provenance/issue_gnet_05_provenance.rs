#[test]
fn issue_gnet_05_provenance_real_emitted_cpu_same_names_changed_computation() {
    static NEXT: AtomicUsize = AtomicUsize::new(0);
    let dir = std::env::temp_dir().join(format!(
        "invar-gnet-provenance-{}-{}",
        std::process::id(),
        NEXT.fetch_add(1, Ordering::Relaxed)
    ));
    fs::create_dir(&dir).unwrap();
    let driver = r#"
#include <iostream>
int main() {
    gnet_w input[1]={5}, output[8]={}; gnet_u trace[7000]={};
    gnet_run(input,output,trace,1000,1000,1000);
    for (auto word:output) std::cout << word << ' ';
}
"#;
    // Both candidates use identical entry and filenames. The real compiled
    // instruction bytes must determine the observed computation.
    for (source, result) in [
        (SOURCE.to_vec(), 15),
        (SOURCE.replace_bytes(b"n * 3", b"n * 4"), 20),
    ] {
        let artifact = compile(&source, "calc", Target::Cpu);
        artifact
            .verify_artifact_bytes(artifact.artifact().source().as_bytes())
            .unwrap();
        fs::write(
            dir.join("candidate.cpp"),
            format!("{}\n{driver}", artifact.artifact().source()),
        )
        .unwrap();
        child_deadline::cxx(
            child_deadline::CXX17_UBSAN_O1,
            &dir.join("candidate.cpp"),
            &dir.join("candidate"),
        );
        let output = Command::new(dir.join("candidate")).output().unwrap();
        assert!(
            output.status.success(),
            "{}",
            String::from_utf8_lossy(&output.stderr)
        );
        let words: Vec<u64> = String::from_utf8(output.stdout)
            .unwrap()
            .split_whitespace()
            .map(|n| n.parse().unwrap())
            .collect();
        let oracle = artifact
            .observe_oracle(
                &[eval::Value::I32(5)],
                oracle::Limits {
                    fuel: 1000,
                    transitions: 1000,
                    trace_events: 1000,
                    ..oracle::Limits::default()
                },
            )
            .unwrap();
        let observed = oracle.observation();
        assert_eq!(
            words,
            vec![
                0,
                result,
                0,
                0,
                observed.semantic.steps_used,
                observed.transitions,
                observed.max_frames as u64,
                observed.events.len() as u64
            ]
        );
        println!(
            "{}",
            json!({"backend":"emitted_cpu_ubsan", "artifact_id":artifact.id(), "words":words})
        );
    }
    fs::remove_dir_all(dir).unwrap();
}
